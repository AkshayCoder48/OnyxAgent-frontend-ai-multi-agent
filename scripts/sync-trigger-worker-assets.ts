// ============================================================================
// Sync the app's sandbox-facing assets into the Trigger.dev worker package.
//
// The worker (trigger-worker/) is a SEPARATE deployable package — it cannot
// import from the app's src/ tree, so it carries a MIRROR of one app asset:
//
//   HEADLESS_RUNNER_PY (src/lib/e2b/headless-agent.ts) — the Python agent
//   loop the worker writes into every task sandbox. The app deploys the
//   same source into its own (foreground) sandboxes; both copies MUST
//   stay byte-identical or the file protocol (run.json /
//   agent_status.json / chat_history.json) and RUNNER_VERSION drift.
//
// The MASTER SKILL LIBRARY is NOT mirrored: bundling the ~2 MB zip into the
// worker crashed the trigger.dev build service (verified 2026-11-14 — a
// stub deploys fine, the full literal dies with "The service was stopped").
// The worker instead FETCHES it at runtime from the app:
//   ${appUrl}/api/skills/master-library  (see src/app/api/skills/master-library/)
// which also keeps a single source of truth — skills update with the app,
// no worker re-deploy needed.
//
// Run after editing the runner source:
//   bun run scripts/sync-trigger-worker-assets.ts
// ============================================================================

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

function read(rel: string): string {
  return readFileSync(join(repoRoot, rel), "utf8");
}

/** Extract a `export const NAME: string = String.raw\`...\`` payload. */
function extractRawString(source: string, name: string): string {
  const startMarker = `export const ${name}`;
  const start = source.indexOf(startMarker);
  if (start === -1) throw new Error(`export ${name} not found`);
  const tickStart = source.indexOf("`", start);
  if (tickStart === -1) throw new Error(`${name}: opening backtick not found`);
  // Find the closing unescaped backtick (String.raw keeps \`, so only an
  // unescaped ` terminates). Scan for a ` not preceded by a backslash.
  for (let i = tickStart + 1; i < source.length; i++) {
    if (source[i] === "`" && source[i - 1] !== "\\") {
      return source.slice(tickStart + 1, i);
    }
  }
  throw new Error(`${name}: closing backtick not found`);
}

/** Extract a string literal's value (`export const X = "...";`). */
function extractQuoted(source: string, name: string): string {
  const re = new RegExp(`export const ${name}\\s*=\\s*"([^"]*)"`);
  const m = source.match(re);
  if (!m) throw new Error(`export ${name} (quoted) not found`);
  return m[1]!;
}

/** Extract a bare (unquoted) literal's value (`export const X = 55;`). */
function extractBare(source: string, name: string): string {
  const re = new RegExp(`export const ${name}\\s*=\\s*([^;\\n]+);`);
  const m = source.match(re);
  if (!m) throw new Error(`export ${name} (bare) not found`);
  return m[1]!.trim();
}

let changed = 0;

// ── 1. Runner source ────────────────────────────────────────────────────────
{
  const appSource = read("src/lib/e2b/headless-agent.ts");
  const runnerPy = extractRawString(appSource, "HEADLESS_RUNNER_PY");
  const runnerVersion = /RUNNER_VERSION = (\d+)/.exec(runnerPy)?.[1] ?? "?";
  const target = join(repoRoot, "trigger-worker/src/runner-source.ts");
  const generated =
    `// ============================================================================
// AUTO-GENERATED by scripts/sync-trigger-worker-assets.ts — DO NOT EDIT.
// Mirrored from src/lib/e2b/headless-agent.ts (HEADLESS_RUNNER_PY, runner
// v${runnerVersion}) — keep in sync.
//
// This is the EXACT Python source the app deploys into its own sandbox
// sandboxes. The worker ships its own copy because it is a separate
// deployable package and cannot import from the app's src/ tree. Do not
// edit one without the other: the runner's on-disk protocol (run.json /
// agent_status.json / chat_history.json) and RUNNER_VERSION stamp must stay
// identical.
// ============================================================================

export const HEADLESS_RUNNER_PY: string = String.raw\`` +
    runnerPy +
    "`;\n";
  const before = (() => {
    try {
      return readFileSync(target, "utf8");
    } catch {
      return "";
    }
  })();
  if (before !== generated) {
    writeFileSync(target, generated);
    changed++;
    console.log(`[sync] runner-source.ts rewritten (runner v${runnerVersion}, ${runnerPy.length} chars)`);
  } else {
    console.log(`[sync] runner-source.ts up to date (runner v${runnerVersion})`);
  }
}

if (changed === 0) {
  console.log("[sync] worker asset mirrors up to date");
}
