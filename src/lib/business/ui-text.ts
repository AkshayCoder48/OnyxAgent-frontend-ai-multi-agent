/** Current UI locale for business copy ("en" | "pl"). */
let currentLocale: "en" | "pl" = "en";

export function setBusinessTextLocale(locale: string | undefined) {
  currentLocale = locale === "pl" ? "pl" : "en";
}

/**
 * Business text lookup with {var} interpolation.
 * Falls back to English when a PL key is missing, then to the raw key.
 */
export function bt(key: string, vars?: Record<string, string | number>): string {
  const table = currentLocale === "pl" ? PL : EN;
  let text = table[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

/** Bullet list helper for arrays rendered in UI. */
export function btList(statusKey: string): string {
  return bt(statusKey);
}
